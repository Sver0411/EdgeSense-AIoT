#!/usr/bin/env python3
"""Analyse one EdgeSense experiment: ground truth vs system decisions.

This is the only place where a `truth_category` and a `decision_label` meet. It is
what makes the separation real rather than nominal:

    firmware  -> knows only what it observed          (no truth)
    backend   -> stores decisions and observations    (no truth)
    analysis  -> joins truth to decisions, off-device (this file)

Usage:
    python3 experiments/analyze_experiment.py --exp experiments/EXP-000
    python3 experiments/analyze_experiment.py --exp experiments/EXP-006 \\
        --require-categories sensor_fault,shared_event,normal

Exit status:
    0  analysis written
    1  a schema problem, or a required truth category had no windows
    2  usage problem

Output is deterministic: the same inputs produce byte-identical files, so a diff
of two runs is meaningful and no wall-clock timestamp is embedded.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from edgeeval import load_decisions, load_manifest, load_truth
from edgeeval.metrics import (
    PRIMARY_LABELS,
    MissingTruthCategory,
    PrimaryMetrics,
    compute_primary_metrics,
    match_windows,
)
from edgeeval.schema import PRIMARY_RQ_CATEGORIES, SchemaError

REPO_ROOT = Path(__file__).resolve().parent.parent


def _fmt(value: float | None, digits: int = 4) -> str:
    return "not_defined" if value is None else f"{value:.{digits}f}"


def _proportion(mapping: dict[str, object]) -> str:
    if not mapping.get("defined", False):
        return f"not_defined (0/{mapping['denominator']})"
    return (
        f"{mapping['value']:.4f} "
        f"[{mapping['ci95_low']:.4f}, {mapping['ci95_high']:.4f}] "
        f"({mapping['numerator']}/{mapping['denominator']})"
    )


def _metrics_to_dict(manifest: dict, metrics: PrimaryMetrics) -> dict:
    return {
        "exp_id": manifest["exp_id"],
        "input_mode": manifest["input_mode"],
        "fault_taxonomy_version": manifest["fault_taxonomy_version"],
        "manifest_status": manifest["status"],
        "windows": {
            "total": metrics.windows_total,
            "in_primary_analysis": metrics.windows_in_primary,
            "excluded": metrics.windows_excluded,
            "excluded_by_category": metrics.excluded_by_category,
            "by_truth_category": metrics.counts,
        },
        "confusion_matrix": metrics.confusion,
        "primary_rq": {
            "fault_to_event": metrics.fault_to_event.as_dict(),
            "event_to_fault": metrics.event_to_fault.as_dict(),
            "shared_event_recall": metrics.shared_event_recall.as_dict(),
            "false_alarm_rate": metrics.false_alarm_rate.as_dict(),
        },
        "per_class": {
            label: {
                "support": entry.support,
                "predicted": entry.predicted,
                "true_positive": entry.true_positive,
                "precision": entry.precision.as_dict(),
                "recall": entry.recall.as_dict(),
                "f1": entry.f1,
            }
            for label, entry in metrics.per_class.items()
        },
        "per_scenario": [
            {
                "scenario": scenario.scenario,
                "windows": scenario.windows,
                "fault_to_event": scenario.fault_to_event.as_dict(),
                "event_to_fault": scenario.event_to_fault.as_dict(),
                "shared_event_recall": scenario.shared_event_recall.as_dict(),
                "false_alarm_rate": scenario.false_alarm_rate.as_dict(),
            }
            for scenario in metrics.per_scenario
        ],
        "per_family": [
            {
                "truth_category": entry.truth_category,
                "family": entry.family,
                "windows": entry.windows,
                "decisions": dict(sorted(entry.decisions.items())),
            }
            for entry in metrics.per_family
        ],
    }


def _render_markdown(manifest: dict, metrics: PrimaryMetrics) -> str:
    lines: list[str] = []
    lines.append(f"# Experiment analysis — {manifest['exp_id']}")
    lines.append("")
    lines.append(
        f"input_mode: `{manifest['input_mode']}` · "
        f"taxonomy: `{manifest['fault_taxonomy_version']}` · "
        f"manifest status: `{manifest['status']}`"
    )
    lines.append("")
    lines.append(
        "Generated by `experiments/analyze_experiment.py`. Do not edit: these numbers "
        "exist so that no number is ever typed by hand."
    )
    lines.append("")

    lines.append("## Window accounting")
    lines.append("")
    lines.append("| item | count |")
    lines.append("|---|---:|")
    lines.append(f"| decision windows, total | {metrics.windows_total} |")
    lines.append(f"| in the primary analysis | {metrics.windows_in_primary} |")
    lines.append(f"| excluded from it | {metrics.windows_excluded} |")
    for category, count in metrics.excluded_by_category.items():
        lines.append(f"| ... excluded: `{category}` | {count} |")
    for label in PRIMARY_LABELS:
        lines.append(f"| truth = `{label}` | {metrics.counts.get(label, 0)} |")
    lines.append("")

    lines.append("## Confusion matrix (primary analysis)")
    lines.append("")
    header = "| truth \\ decision | " + " | ".join(f"`{label}`" for label in PRIMARY_LABELS) + " |"
    lines.append(header)
    lines.append("|---|" + "---:|" * len(PRIMARY_LABELS))
    for truth in PRIMARY_LABELS:
        row = [f"| `{truth}` "]
        for decision in PRIMARY_LABELS:
            row.append(f"| {metrics.confusion[truth][decision]} ")
        lines.append("".join(row) + "|")
    lines.append("")

    lines.append("## Primary results")
    lines.append("")
    lines.append("| metric | value (95% Wilson CI, counts) |")
    lines.append("|---|---|")
    lines.append(f"| fault -> event rate | {_proportion(metrics.fault_to_event.as_dict())} |")
    lines.append(f"| event -> fault rate | {_proportion(metrics.event_to_fault.as_dict())} |")
    lines.append(f"| shared-event recall | {_proportion(metrics.shared_event_recall.as_dict())} |")
    lines.append(f"| false alarm rate (truth = normal) | {_proportion(metrics.false_alarm_rate.as_dict())} |")
    lines.append("")
    lines.append(
        "No threshold is applied and none is implied: the rates are reported as "
        "measured, and the primary hypothesis is allowed to fail."
    )
    lines.append("")

    lines.append("## Per class")
    lines.append("")
    lines.append("| class | support | predicted | TP | precision | recall | F1 |")
    lines.append("|---|---:|---:|---:|---|---|---:|")
    for label, entry in metrics.per_class.items():
        lines.append(
            f"| `{label}` | {entry.support} | {entry.predicted} | {entry.true_positive} | "
            f"{_proportion(entry.precision.as_dict())} | "
            f"{_proportion(entry.recall.as_dict())} | {_fmt(entry.f1)} |"
        )
    lines.append("")

    lines.append("## Per scenario")
    lines.append("")
    lines.append(
        "Reported alongside the pooled figures on purpose: an aggregate can hide a "
        "scenario that failed completely."
    )
    lines.append("")
    lines.append("| scenario | windows | fault->event | event->fault | shared recall | false alarm |")
    lines.append("|---|---:|---|---|---|---|")
    for scenario in metrics.per_scenario:
        lines.append(
            f"| `{scenario.scenario}` | {scenario.windows} | "
            f"{_proportion(scenario.fault_to_event.as_dict())} | "
            f"{_proportion(scenario.event_to_fault.as_dict())} | "
            f"{_proportion(scenario.shared_event_recall.as_dict())} | "
            f"{_proportion(scenario.false_alarm_rate.as_dict())} |"
        )
    lines.append("")

    lines.append("## Per family")
    lines.append("")
    lines.append("| truth category | family | windows | decisions |")
    lines.append("|---|---|---:|---|")
    for entry in metrics.per_family:
        decisions = ", ".join(f"`{label}`={count}" for label, count in sorted(entry.decisions.items()))
        lines.append(f"| `{entry.truth_category}` | `{entry.family}` | {entry.windows} | {decisions} |")
    lines.append("")

    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--exp", required=True, help="experiment directory, e.g. experiments/EXP-000")
    parser.add_argument(
        "--require-categories",
        default=",".join(PRIMARY_RQ_CATEGORIES),
        help="truth categories whose absence makes a metric undefined (default: the primary set)",
    )
    parser.add_argument("--out-dir", default=None, help="defaults to <exp>/results/analysis")
    args = parser.parse_args(argv)

    exp_dir = Path(args.exp)
    if not exp_dir.is_absolute():
        exp_dir = (REPO_ROOT / exp_dir).resolve()
    if not exp_dir.is_dir():
        print(f"FAIL no such experiment directory: {exp_dir}")
        return 2

    required = tuple(item.strip() for item in args.require_categories.split(",") if item.strip())
    out_dir = Path(args.out_dir) if args.out_dir else exp_dir / "results" / "analysis"

    try:
        manifest = load_manifest(exp_dir / "manifest.json")
        episodes = load_truth(exp_dir / "truth" / "episodes.csv")
        decisions = load_decisions(exp_dir / "results" / "decisions.csv")
        pairs = match_windows(decisions, episodes)
        metrics = compute_primary_metrics(pairs, required)
    except SchemaError as exc:
        print(f"FAIL schema: {exc}")
        return 1
    except MissingTruthCategory as exc:
        print(f"FAIL undefined metric: {exc}")
        return 1

    out_dir.mkdir(parents=True, exist_ok=True)
    payload = _metrics_to_dict(manifest, metrics)
    (out_dir / "metrics.json").write_text(
        json.dumps(payload, indent=2, ensure_ascii=False, sort_keys=True) + "\n", encoding="utf-8"
    )
    (out_dir / "report.md").write_text(_render_markdown(manifest, metrics), encoding="utf-8")

    print(f"PASS {manifest['exp_id']}: {metrics.windows_in_primary} windows in the primary analysis")
    print(f"     fault->event {_proportion(metrics.fault_to_event.as_dict())}")
    print(f"     event->fault {_proportion(metrics.event_to_fault.as_dict())}")
    print(f"     shared-event recall {_proportion(metrics.shared_event_recall.as_dict())}")
    print(f"     wrote {out_dir.relative_to(REPO_ROOT) if out_dir.is_relative_to(REPO_ROOT) else out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
